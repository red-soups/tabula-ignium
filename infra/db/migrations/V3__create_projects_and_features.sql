
-- ============================================
-- 1. PROJECTS
-- ============================================

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    name VARCHAR(200) NOT NULL,

    description TEXT,

    created_by BIGINT NOT NULL,

    updated_by BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_projects_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT fk_projects_created_by
        FOREIGN KEY (created_by)
        REFERENCES users(id),

    CONSTRAINT fk_projects_updated_by
        FOREIGN KEY (updated_by)
        REFERENCES users(id)
);

-- 프로젝트 소유자별 조회
CREATE INDEX idx_projects_user_id
    ON projects (user_id);


-- ============================================
-- 2. PROJECT_REGIONS
-- ============================================

CREATE TABLE project_regions (
    project_id BIGINT NOT NULL,

    region_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_project_regions
        PRIMARY KEY (project_id, region_id),

    CONSTRAINT fk_project_regions_project
        FOREIGN KEY (project_id)
        REFERENCES projects(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_project_regions_region
        FOREIGN KEY (region_id)
        REFERENCES regions(id)
);

-- 특정 지역을 사용하는 프로젝트 조회
CREATE INDEX idx_project_regions_region_id
    ON project_regions (region_id);


-- ============================================
-- 3. FEATURES
-- ============================================

CREATE TABLE features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(100) NOT NULL UNIQUE,

    name VARCHAR(200) NOT NULL,

    description TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================
-- 4. PROJECT_FEATURES
-- ============================================

CREATE TABLE project_features (
    project_id BIGINT NOT NULL,

    feature_id BIGINT NOT NULL,

    configuration JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_project_features
        PRIMARY KEY (project_id, feature_id),

    CONSTRAINT fk_project_features_project
        FOREIGN KEY (project_id)
        REFERENCES projects(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_project_features_feature
        FOREIGN KEY (feature_id)
        REFERENCES features(id)
);

-- 특정 기능을 사용하는 프로젝트 조회
CREATE INDEX idx_project_features_feature_id
    ON project_features (feature_id);
