-- ============================================
-- 1. KOREA FIRE POINTS
-- ============================================

CREATE TABLE fire_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sensor VARCHAR(20) NOT NULL,
    satellite VARCHAR(30) NOT NULL,

    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,

    acq_date DATE NOT NULL,
    acq_time_utc CHAR(4) NOT NULL,

    -- MODIS는 숫자, VIIRS는 n/h 같은 문자를 사용하므로 문자열로 저장한다.
    confidence VARCHAR(20) NOT NULL,
    confidence_level VARCHAR(30) NOT NULL,

    frp DOUBLE PRECISION NOT NULL,
    daynight CHAR(1) NOT NULL,
    bright_fire DOUBLE PRECISION NOT NULL,
    bright_bg DOUBLE PRECISION NOT NULL,
    scan DOUBLE PRECISION NOT NULL,
    track DOUBLE PRECISION NOT NULL,
    version VARCHAR(30) NOT NULL,
    type SMALLINT NOT NULL,
    type_inferred SMALLINT NOT NULL,
    data_source VARCHAR(30) NOT NULL,

    -- 컬럼명에 KST가 명시되어 있으므로 시간대 없는 한국 현지 시각으로 보존한다.
    acq_datetime_kst TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    period CHAR(7) NOT NULL,

    cell_row SMALLINT NOT NULL,
    cell_col SMALLINT NOT NULL,
    fine_row SMALLINT NOT NULL,
    fine_col SMALLINT NOT NULL,

    source VARCHAR(30) NOT NULL,
    carrier SMALLINT NOT NULL,

    weight DOUBLE PRECISION NOT NULL,
    weight_low DOUBLE PRECISION,
    weight_high DOUBLE PRECISION,
    frp_weight DOUBLE PRECISION,
    frp_weight_low DOUBLE PRECISION,
    frp_weight_high DOUBLE PRECISION,

    location GEOMETRY(POINT, 4326)
        GENERATED ALWAYS AS (
            ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)
        ) STORED,

    imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_fire_points_latitude
        CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_fire_points_longitude
        CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_fire_points_daynight
        CHECK (daynight IN ('D', 'N')),
    CONSTRAINT ck_fire_points_period
        CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
);


-- ============================================
-- 2. CSV IMPORT
-- ============================================

-- compose.yaml에서 infra/data/regions를 /region-data로 읽기 전용 마운트한다.
COPY fire_points (
    sensor,
    satellite,
    latitude,
    longitude,
    acq_date,
    acq_time_utc,
    confidence,
    confidence_level,
    frp,
    daynight,
    bright_fire,
    bright_bg,
    scan,
    track,
    version,
    type,
    type_inferred,
    data_source,
    acq_datetime_kst,
    period,
    cell_row,
    cell_col,
    fine_row,
    fine_col,
    source,
    carrier,
    weight,
    weight_low,
    weight_high,
    frp_weight,
    frp_weight_low,
    frp_weight_high
)
FROM '/region-data/korea_fire_points.csv'
WITH (
    FORMAT CSV,
    HEADER TRUE,
    NULL ''
);


-- ============================================
-- 3. LOOKUP INDEXES
-- ============================================

-- 관심지역 경계와 화재 지점을 공간 조인할 때 사용한다.
CREATE INDEX idx_fire_points_location_gist
    ON fire_points USING GIST (location);

-- 최신 관측과 센서별 관측을 조회할 때 사용한다.
CREATE INDEX idx_fire_points_acquired_at
    ON fire_points (acq_date DESC, acq_time_utc DESC);

CREATE INDEX idx_fire_points_sensor_acquired_at
    ON fire_points (sensor, acq_date DESC, acq_time_utc DESC);

-- 월별 0.5도 및 세부 격자 조회에 사용한다.
CREATE INDEX idx_fire_points_period_cell
    ON fire_points (period, cell_row, cell_col);

CREATE INDEX idx_fire_points_period_fine_cell
    ON fire_points (period, fine_row, fine_col);


-- ============================================
-- 4. IMPORT VALIDATION
-- ============================================

DO $$
DECLARE
    total_count BIGINT;
    modis_count BIGINT;
    viirs_count BIGINT;
BEGIN
    SELECT COUNT(*),
           COUNT(*) FILTER (WHERE sensor = 'MODIS'),
           COUNT(*) FILTER (WHERE sensor = 'VIIRS')
      INTO total_count, modis_count, viirs_count
      FROM fire_points;

    IF total_count <> 74729
       OR modis_count <> 30014
       OR viirs_count <> 44715 THEN
        RAISE EXCEPTION
            'Korea fire point import failed: total %, MODIS %, VIIRS %',
            total_count, modis_count, viirs_count;
    END IF;
END;
$$;

ANALYZE fire_points;
