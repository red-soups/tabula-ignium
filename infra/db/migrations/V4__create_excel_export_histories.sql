
-- ============================================
-- EXCEL_EXPORT_HISTORIES
-- ============================================

CREATE TABLE excel_export_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    project_id BIGINT,

    file_name VARCHAR(255),

    file_url TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    completed_at TIMESTAMPTZ,

    downloaded_at TIMESTAMPTZ,

    CONSTRAINT fk_excel_export_histories_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT fk_excel_export_histories_project
        FOREIGN KEY (project_id)
        REFERENCES projects(id)
        ON DELETE SET NULL
);


-- ============================================
-- INDEXES
-- ============================================

-- 사용자별 최신 내보내기 이력 조회
CREATE INDEX idx_excel_export_histories_user_created
    ON excel_export_histories (user_id, created_at DESC);

-- 프로젝트별 내보내기 이력 조회
CREATE INDEX idx_excel_export_histories_project_id
    ON excel_export_histories (project_id);
