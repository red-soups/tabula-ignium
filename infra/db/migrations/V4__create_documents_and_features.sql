-- ============================================
-- 1. DOCUMENTS
-- ============================================

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    name VARCHAR(200) NOT NULL,

    description TEXT,

    created_by BIGINT NOT NULL,

    updated_by BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_documents_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT fk_documents_created_by
        FOREIGN KEY (created_by)
        REFERENCES users(id),

    CONSTRAINT fk_documents_updated_by
        FOREIGN KEY (updated_by)
        REFERENCES users(id)
);

-- 문서 소유자별 조회
CREATE INDEX idx_documents_user_id
    ON documents (user_id);


-- ============================================
-- 2. DOCUMENT_REGIONS
-- ============================================

CREATE TABLE document_regions (
    document_id BIGINT NOT NULL,

    region_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_document_regions
        PRIMARY KEY (document_id, region_id),

    CONSTRAINT fk_document_regions_document
        FOREIGN KEY (document_id)
        REFERENCES documents(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_document_regions_region
        FOREIGN KEY (region_id)
        REFERENCES regions(id)
);

-- 특정 지역을 사용하는 문서 조회
CREATE INDEX idx_document_regions_region_id
    ON document_regions (region_id);


-- ============================================
-- 3. FEATURES
-- ============================================

CREATE TABLE features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(100) NOT NULL UNIQUE,

    name VARCHAR(200) NOT NULL,

    description TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================
-- 4. DOCUMENT_FEATURES
-- ============================================

CREATE TABLE document_features (
    document_id BIGINT NOT NULL,

    feature_id BIGINT NOT NULL,

    configuration JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_document_features
        PRIMARY KEY (document_id, feature_id),

    CONSTRAINT fk_document_features_document
        FOREIGN KEY (document_id)
        REFERENCES documents(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_document_features_feature
        FOREIGN KEY (feature_id)
        REFERENCES features(id)
);

-- 특정 기능을 사용하는 문서 조회
CREATE INDEX idx_document_features_feature_id
    ON document_features (feature_id);
