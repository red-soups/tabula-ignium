CREATE TABLE document_export_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    storage_provider VARCHAR(20) NOT NULL DEFAULT 'LOCAL',
    file_path VARCHAR(1000) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_document_export_histories_document
        FOREIGN KEY (document_id) REFERENCES documents(id) ON DELETE CASCADE,
    CONSTRAINT fk_document_export_histories_created_by
        FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT chk_document_export_histories_file_size CHECK (file_size > 0)
);

CREATE INDEX idx_document_export_histories_created_by_created_at
    ON document_export_histories (created_by, created_at DESC);

CREATE INDEX idx_document_export_histories_document_id
    ON document_export_histories (document_id);

COMMENT ON COLUMN document_export_histories.file_path IS
    'LOCAL에서는 저장 루트 기준 상대 경로, S3 전환 후에는 object key';
