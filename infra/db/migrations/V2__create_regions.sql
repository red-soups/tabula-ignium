
-- ============================================
-- 1. REGIONS
-- ============================================

CREATE TABLE regions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    region_code VARCHAR(50) NOT NULL UNIQUE,

    name VARCHAR(200) NOT NULL,

    country_code VARCHAR(2) NOT NULL,

    region_type VARCHAR(30),

    boundary GEOMETRY(MULTIPOLYGON, 4326)
);

-- 공간 검색용 GiST 인덱스
CREATE INDEX idx_regions_boundary_gist
    ON regions USING GIST (boundary);

-- 국가별 지역 조회용 인덱스
CREATE INDEX idx_regions_country_code
    ON regions (country_code);


-- ============================================
-- 2. USER_INTERESTED_REGIONS
-- ============================================

CREATE TABLE user_interested_regions (
    user_id BIGINT NOT NULL,

    region_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_user_interested_regions
        PRIMARY KEY (user_id, region_id),

    CONSTRAINT fk_user_interested_regions_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_user_interested_regions_region
        FOREIGN KEY (region_id)
        REFERENCES regions(id)
        ON DELETE CASCADE
);

-- 지역별 관심 사용자 조회용 인덱스
CREATE INDEX idx_user_interested_regions_region_id
    ON user_interested_regions (region_id);
